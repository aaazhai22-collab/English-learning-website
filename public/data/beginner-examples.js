const normalized = value => String(value || '').trim().toLowerCase().replace(/[’‘]/g,"'").replace(/\s+/g,' ');
export const curatedBeginnerExamples = Object.freeze(Object.fromEntries(editorialRows.map(([word,sentence,translation,sense,target])=>[normalized(word),Object.freeze({sentence,translation,sense,target:target||word,source:'beginner-editorial'})])));
export const beginnerExampleMetadata = Object.freeze({version:1,curatedCount:Object.keys(curatedBeginnerExamples).length,policy:'完整短句优先；不裁断原句；保留原有多义项例句。',maxCuratedWords:14});
export function exampleWordCount(sentence){return (String(sentence||'').match(/[A-Za-z]+(?:['’-][A-Za-z]+)*/g)||[]).length;}
export function exampleDifficulty(example){
  const sentence=String(example?.sentence||''),length=exampleWordCount(sentence);
  if(!sentence.trim()||!String(example?.translation||'').trim())return Infinity;
  const clauses=(sentence.match(/\b(?:although|though|whereas|unless|whether|whose|which|because|while|despite|whenever|wherever|provided that|rather than)\b/gi)||[]).length;
  const conjunctions=(sentence.match(/\b(?:that|who|when|where|if|but|yet)\b/gi)||[]).length;
  const punctuation=(sentence.match(/[;:—]/g)||[]).length;
  const abstractPatterns=(sentence.match(/\b(?:not only|less .+? than|insofar|thereby|neither|nor|had been|would have|could have)\b/gi)||[]).length;
  return length+clauses*7+conjunctions*3+punctuation*3+abstractPatterns*6+Math.max(0,length-14)*2;
}
export function validateBeginnerExample(example,word){
  if(!example||!String(example.sentence||'').trim()||!String(example.translation||'').trim())throw new Error(`缺少例句或中译：${word}`);
  if(!/[.!?][”’"']?$/.test(example.sentence))throw new Error(`例句必须完整结束：${word}`);
  const target=normalized(example.target||word),sentence=normalized(example.sentence);
  const escaped=target.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
  if(!target||!new RegExp(`(^|[^a-z])${escaped}(?=$|[^a-z])`,'i').test(sentence))throw new Error(`例句缺少目标词或明确词形：${word}`);
  return true;
}
export function selectBeginnerExample(word){
  if(!word||typeof word!=='object')throw new Error('请选择一个词条');
  if(word.lexiconType==='grammar'||word.collectionId==='grammar-handbook'){
    const example=word.examples?.find(value=>value?.sentence&&value?.translation);
    if(!example)throw new Error(`这个语法词条没有可用例句：${word.word||''}`);
    return {...example,pos:example.pos||word.pos||'',sense:example.sense||word.meaning||'',source:'grammar-handbook',level:'手册例句'};
  }
  const key=normalized(word.word),curated=curatedBeginnerExamples[key];
  if(curated){const value={...curated,pos:word.pos||word.examples?.[0]?.pos||'',collocations:word.collocations||word.examples?.[0]?.collocations||[],level:'基础例句'};validateBeginnerExample(value,word.word);return value;}
  const source=Array.isArray(word.examples)?word.examples:[];
  const candidates=[...source,...(word.sentence?[{pos:word.pos,sense:word.meaning,sentence:word.sentence,translation:word.translation,collocations:word.collocations}]:[])].filter(ex=>ex&&String(ex.sentence||'').trim()&&String(ex.translation||'').trim());
  if(!candidates.length)throw new Error(`这个词条没有可用的完整例句：${word.word||''}`);
  const value=candidates.map((example,index)=>({example,index,score:exampleDifficulty(example)})).sort((a,b)=>a.score-b.score||a.index-b.index)[0].example;
  return {...value,pos:value.pos||word.pos||'',sense:value.sense||word.meaning||'',source:'existing-short-example',level:'基础例句'};
}
