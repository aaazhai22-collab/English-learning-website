async function collect(directory, prefix = '') {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = `${prefix}/${entry.name}`;
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) await collect(filename, relative);
    else if (entry.isFile()) {
      const bytes = await readFile(filename);
      const remote = remoteAssets[relative];
      if (remote) {
        if (bytes.length !== remote.size || createHash('sha256').update(bytes).digest('hex') !== remote.sha256) throw new Error(`Pinned OCR asset changed: ${relative}`);
      } else assets[relative] = { type: types[path.extname(entry.name)] || 'application/octet-stream', body: bytes.toString('base64') };
    }
    else throw new Error('Only regular files can be packaged');
  }
}
await collect(path.join(root, 'public'));
const catalog = JSON.parse(await readFile(path.join(root, 'public/data/catalog.json'), 'utf8'));
const speechChunks = buildPublicSpeechEntries(catalog).map(splitSpeechText);
const code = `// Generated by scripts/build.mjs. Edit public/ and worker/ source files.\nconst assets = ${JSON.stringify(assets)};\nconst remoteAssets = ${JSON.stringify(remoteAssets)};\nconst speechChunks = ${JSON.stringify(speechChunks)};\nconst createFreeReadingAnalyzer = ${createFreeReadingAnalyzer.toString()};\nconst createReadingAPI = ${createReadingAPI.toString()};\nconst createSiteHandler = ${createSiteHandler.toString()};\nexport default createSiteHandler(assets, speechChunks, createReadingAPI(createFreeReadingAnalyzer()), remoteAssets);\n`;
const compressedSize = gzipSync(code, { level: 9 }).length;
if (compressedSize >= 10_000_000) throw new Error(`Worker exceeds the 10 MB compressed script budget: ${compressedSize} bytes`);
await mkdir(path.join(root, 'dist/server'), { recursive: true });
await mkdir(path.join(root, 'dist/.openai'), { recursive: true });
await writeFile(path.join(root, 'dist/server/index.js'), code);
await writeFile(path.join(root, 'dist/.openai/hosting.json'), await readFile(path.join(root, '.openai/hosting.json')));
console.log(`Built Worker with ${Object.keys(assets).length} embedded assets, ${Object.keys(remoteAssets).length} pinned same-origin OCR resources and ${speechChunks.length} public speech entries. Gzip script: ${compressedSize} bytes (<10 MB).`);
