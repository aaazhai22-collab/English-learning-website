import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdir,writeFile,readFile } from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
const page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
await mkdir('qa',{recursive:true});
try{
 await page.goto('http://localhost:5173/',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:/从看懂/}).waitFor();
 await page.screenshot({path:'qa/desktop-home.png',fullPage:true});
 await page.getByRole('button',{name:/开始学习/}).click();
 await page.locator('.sentence-card').first().waitFor();
 assert.equal(await page.locator('.sentence-card').count(),17);
 await page.locator('.sentence-card .word-token[data-word="As"]').first().click();
 await page.locator('dialog[open]').waitFor();
 assert.ok((await page.locator('dialog').innerText()).includes('随着'));
 await page.screenshot({path:'qa/word-popup.png'});
 await page.getByRole('button',{name:'收藏到学习库',exact:true}).click();
 await page.locator('.grammar-item button').first().click();
 await page.getByRole('button',{name:'收藏到学习库',exact:true}).click();
 await page.locator('[data-action="save-chunk"]').first().click();
 await page.getByRole('button',{name:'收藏到学习库',exact:true}).click();
 await page.goto('http://localhost:5173/#/words');
 await page.locator('.word-card').first().waitFor();
 assert.ok(await page.locator('.word-card').count()>=3);
 await page.selectOption('#word-kind','grammar');
 assert.ok(await page.locator('.word-card').count()>=2);
 await page.reload({waitUntil:'networkidle'});
 assert.ok((await page.locator('main').innerText()).includes('As')||(await page.locator('main').innerText()).includes('as'));
 await page.goto('http://localhost:5173/#/read/older-adults');
 await page.selectOption('#reading-mode','exam');
 assert.equal(await page.locator('.inline-listen').count(),0);
 assert.equal(await page.locator('.word-token[data-action]').count(),0);
 for(const [id,letter]of Object.entries({q1:'A',q2:'C',q3:'A',q4:'B',q5:'C'}))await page.locator(`input[data-question="${id}"][value="${letter}"]`).check({force:true});
 await page.locator('[data-action="submit"]').click();
 await page.locator('.result-strip').waitFor();
 assert.ok((await page.locator('.result-strip').innerText()).includes('80%'));
 await page.locator('[data-action="evidence"]').first().click();
 assert.ok(await page.locator('.inline-sentence.highlight').count()>0);
 await page.goto('http://localhost:5173/#/review');
 assert.ok(await page.locator('.review-card').count()>=1);
 await page.locator('[data-action="review-word"]').first().click();
 await page.getByRole('button',{name:'想好后，揭晓解释'}).click();
 await page.locator('[data-action="rate-word"][data-rating="good"]').click();
 await page.goto('http://localhost:5173/#/import');
 await page.fill('#import-text','Passage: Import Test\n\nStudents learn a language by reading carefully. They can listen to sentences and collect useful words for later review.\n\n1. How can students learn?\nA. By reading\nB. By sleeping\nC. By driving\nD. By cooking');
 await page.locator('[data-action="parse-import"]').click();
 await page.locator('#import-preview').waitFor();
 assert.ok((await page.locator('#import-preview').innerText()).includes('1 道题'));
 await page.locator('[data-action="save-import"]').click();
 await page.locator('.reader-heading h1').filter({hasText:'Import Test'}).waitFor();
 await page.getByRole('tab',{name:'阅读练习'}).click();
 await page.locator('input[data-question="q1"][value="A"]').check({force:true});
 await page.locator('[data-action="submit"]').click();
 assert.ok((await page.locator('.result-strip').innerText()).includes('待核实'));
 await page.goto('http://localhost:5173/#/profile');
 await page.fill('#profile-minutes','45');
 await page.getByRole('button',{name:/保存学习设置/}).click();
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.inputValue('#profile-minutes'),'45');
 await page.fill('#ai-key','test-only-session-sentinel');
 await page.locator('[data-action="configure-ai"]').click();
 assert.ok(!(await page.evaluate(()=>JSON.stringify({...localStorage}))).includes('test-only-session-sentinel'));
 const downloadPromise=page.waitForEvent('download');
 await page.locator('[data-action="backup"]').click();
 const download=await downloadPromise;assert.match(download.suggestedFilename(),/backup/);
 const backupBytes=await readFile(await download.path());assert.ok(!backupBytes.toString().includes('test-only-session-sentinel'));
 await page.locator('#restore-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:backupBytes});
 await page.getByRole('button',{name:'合并备份',exact:true}).click();
 assert.equal(await page.inputValue('#profile-minutes'),'45');
 await page.goto('http://localhost:5173/');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'qa/mobile-home.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 const speechPage=await context.newPage();await speechPage.addInitScript(()=>Object.defineProperty(window,'speechSynthesis',{value:undefined}));
 await speechPage.goto('http://localhost:5173/#/read/older-adults',{waitUntil:'networkidle'});
 await speechPage.getByRole('tab',{name:'逐句精读'}).click();
 const audioResponse=speechPage.waitForResponse(r=>r.url().includes('/api/reading/tts?'),{timeout:25000});
 await speechPage.locator('.sentence-head [data-action="speak"]').first().click();
 const audio=await audioResponse;assert.equal(audio.status(),200);assert.match(audio.headers()['content-type'],/audio/);
 await speechPage.locator('.speaking-bar button').click();await speechPage.close();
 await page.getByRole('button',{name:/开始学习/}).click();
 await page.screenshot({path:'qa/mobile-reading.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: dashboard, 17-sentence reading, word/grammar/phrase collection, persistence, independent 80% scoring, evidence, review, import without answer, profile, backup, mobile layout.');
}finally{await writeFile('qa/browser-errors.json',JSON.stringify(errors));await browser.close();}
