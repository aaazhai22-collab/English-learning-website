import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createSiteHandler } from '../worker/index.js';
import { createReadingAPI } from '../worker/reading-api.js';
import { buildPublicSpeechEntries, splitSpeechText } from './catalog-utils.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.md': 'text/plain; charset=utf-8', '.png': 'image/png', '.svg': 'image/svg+xml' };
const assets = {};
async function collect(directory, prefix = '') {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = `${prefix}/${entry.name}`;
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) await collect(filename, relative);
    else if (entry.isFile()) assets[relative] = { type: types[path.extname(entry.name)] || 'application/octet-stream', body: (await readFile(filename)).toString('base64') };
    else throw new Error('Only regular files can be packaged');
  }
}
await collect(path.join(root, 'public'));
const catalog = JSON.parse(await readFile(path.join(root, 'public/data/catalog.json'), 'utf8'));
const speechChunks = buildPublicSpeechEntries(catalog).map(splitSpeechText);
const code = `// Generated by scripts/build.mjs. Edit public/ and worker/ source files.\nconst assets = ${JSON.stringify(assets)};\nconst speechChunks = ${JSON.stringify(speechChunks)};\nconst createReadingAPI = ${createReadingAPI.toString()};\nconst createSiteHandler = ${createSiteHandler.toString()};\nexport default createSiteHandler(assets, speechChunks, createReadingAPI());\n`;
await mkdir(path.join(root, 'dist/server'), { recursive: true });
await mkdir(path.join(root, 'dist/.openai'), { recursive: true });
await writeFile(path.join(root, 'dist/server/index.js'), code);
await writeFile(path.join(root, 'dist/.openai/hosting.json'), await readFile(path.join(root, '.openai/hosting.json')));
console.log(`Built Worker with ${Object.keys(assets).length} assets and ${speechChunks.length} public speech entries.`);
